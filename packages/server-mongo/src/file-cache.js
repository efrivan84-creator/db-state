// Общее для файловых хуков и файловых RPC-методов: как часто сверяться с
// mtime, прежде чем перечитать файл.
//
// И хук, и метод вызываются на каждой операции, поэтому stat перед каждым
// вызовом был бы самой дорогой их частью. Правка файла применяется в
// пределах минуты — для разработки достаточно, а в бою файлы не меняются.
export const RELOAD_CHECK_MS = 60_000

// Переопределяется опцией reloadCheckMs: 0 — сверяться с mtime на каждом
// вызове (так делают тесты и сборки для разработки), больше — свой интервал.
export function reloadCheckMs(value) {
  return Number.isFinite(value) && value >= 0 ? value : RELOAD_CHECK_MS
}
